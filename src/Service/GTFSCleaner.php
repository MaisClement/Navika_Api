            ],
            'fare_attributes' => [
                'columns' => ['fare_id','provider_id','price','currency_type','payment_method','transfers','agency_id','transfer_duration'],
                'auto' => ['id','provider_id']
            ],
            'frequencies' => [
                'columns' => ['trip_id','start_time','end_time','headway_secs','exact_times','provider_id'],
                'auto' => ['id','provider_id']
            ],
            'feed_info' => [
                'columns' => ['feed_publisher_name','feed_publisher_url','feed_lang','default_lang','feed_start_date','feed_end_date','feed_version','feed_contact_email','feed_contact_url','provider_id'],
                'auto' => ['id','provider_id']
            ],
            'attributions' => [
                'columns' => ['attribution_id','agency_id','route_id','trip_id','organization_name','is_producer','is_operator','is_authority','attribution_url','attribution_email','attribution_phone','provider_id'],
