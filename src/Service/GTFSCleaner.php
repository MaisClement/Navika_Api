                'auto' => ['id','provider_id']
            ],
            'pathways' => [
                'columns' => ['pathway_id','provider_id','from_stop_id','to_stop_id','pathway_mode','is_bidirectional','length','traversal_time','stair_count','max_slope','min_width','signposted_as','reversed_signposted_as'],
                'auto' => ['id','provider_id']
