/**
 * Service de normalisation des fichiers GTFS.
 * - Assainit l'encodage (UTF-8)
 * - Supprime BOM
 * - Normalise fins de ligne \n
 * - Valide et ajuste les colonnes vs schéma BDD (via liste fournie)
 * - Ajoute colonnes manquantes (remplies NULL dans les données)
 * - Ignore colonnes extra (retirées du header utilisé pour import, mais conservées en log)
 * - Préfixe les colonnes identifiants (optionnel, laissé à l'import actuel)
 * - Produit un résumé structuré par fichier
 */
class GTFSCleaner
{
    /** @var array<string,array{columns: string[], auto: string[]}> */
    private array $schemas;

    /** Colonnes à ignorer si présentes dans le fichier mais auto-gérées côté DB */
    private array $autoGeneratedGlobal = ['id'];

    public function __construct()
    {
        // Définition des schémas attendus pour chaque fichier GTFS (adapter selon tables existantes).
        // IMPORTANT: provider_id est géré via SET dans LOAD DATA donc on ne l'exige pas dans le fichier.
        $this->schemas = [
            'agency' => [
                'columns' => ['agency_id','provider_id','agency_name','agency_url','agency_timezone','agency_lang','agency_phone','agency_fare_url','agency_email'],
                'auto' => ['id','provider_id']
            ],
            'routes' => [
                'columns' => ['route_id','provider_id','agency_id','route_short_name','route_long_name','route_desc','route_type','route_url','route_color','route_text_color'],
                'auto' => ['id','provider_id']
            ],
            'calendar' => [
                'columns' => ['service_id','provider_id','monday','tuesday','wednesday','thursday','friday','saturday','sunday','start_date','end_date'],
                'auto' => ['id','provider_id']
            ],
            'calendar_dates' => [
                'columns' => ['service_id','provider_id','date','exception_type'],
                'auto' => ['id','provider_id']
            ],
            'shapes' => [
                'columns' => ['shape_id','provider_id','shape_pt_lat','shape_pt_lon','shape_pt_sequence','shape_dist_traveled'],
                'auto' => ['id','provider_id']
            ],
            'trips' => [
