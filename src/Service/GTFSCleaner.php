                'auto' => ['id','provider_id']
            ],
            'stop_extensions' => [
                'columns' => ['object_id','object_code','provider_id','level_position','elevator','toilet','car','bike','scooter','bus','boat','tram','train','plane'],
                'auto' => ['id','provider_id']
            ],
            'fare_rules' => [
                'columns' => ['fare_id','route_id','origin_id','destination_id','contains_id','provider_id'],
